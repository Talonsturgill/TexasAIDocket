/* oakcliff.js — the chassis for carousel No. 31 (2026-09-21).
 *
 * WHAT THIS IS. The deck "NOT A WARNING" spends nine frames on one Oak Cliff block and the
 * paper that block generates, and argues that the City of Dallas kept every promise it made
 * about its AI cameras and then spent the argument on what a letter is. Nine frames share one
 * light, one stock and one way of seating type, and this file is those three things and nothing
 * else. Every frame's COMPOSITION is written per frame.
 *
 * THE WORLD. AN OAK CLIFF BLOCK IN DALLAS COUNTY AT TEN PAST SEVEN ON A BULK TRASH MORNING, ON
 * THE BLACKLAND PRAIRIE. A sanitation grapple truck on the lane, a curb pile, a bungalow set
 * back behind a live oak, a parkway strip, a porch of 140 mm tongue and groove boards. Inside
 * it, three rooms the same sun reaches through one window on the same side: a committee table
 * in December, that same table with four slips on it, and a council committee room before it
 * fills.
 *
 * THE GROUND IS ONE OF THE MACHINE'S OWN EIGHT CATEGORIES, and that is the whole reason it is
 * this colour. `high grass` is the last item on the detection list the December briefing gave
 * its committee (c7). So the paper this deck is printed on is a thing the software is looking
 * for, and a reader who learns the list on frame 4 has been standing on it since frame 1.
 * #222E16 is St. Augustine in the shade of a live oak, measured at dE76 16.57 from its nearest
 * neighbour in the last six shipped grounds against a floor of 10. A palette checked only by eye
 * is a palette that repeats.
 *
 * THE LIGHT, IN WORDS A FRAME AUTHOR CAN CHECK A DRAWING AGAINST. THE KEY IS LOW IN THE EAST
 * SOUTHEAST, OFF THE CAMERA'S RIGHT SHOULDER, AT 22 DEGREES ABOVE THE PLANE. So every lit face
 * in this deck is a RIGHT face, every left face is the deck's dark side, and every cast runs
 * DOWN AND TO THE LEFT at 2.48 times the object's own height. A 1.7 m person throws about 4.2 m.
 * A 2.9 m truck cab throws about 7.2 m. A 12 mm curled corner of paper throws about 30 mm. If a
 * drawn object has a shadow shorter than itself, or no contact where it meets the ground, that
 * frame is wrong and gets redrawn rather than tuned.
 *
 * WHY THE SUN IS LOW. Seven ten in the morning in late September in Dallas is a real sun at a
 * real elevation, and it is also the elevation this machine's measured failure needs. Across
 * twenty one decks the judges' finding was flatness, and flatness is what a high sun produces:
 * no rake, contact shadows collapsed to a puddle, objects floating. A low sun costs this deck
 * nothing and it is when the brush trucks actually run.
 *
 * THE MOTIF, AND IT IS THE DECK'S ARGUMENT RATHER THAN ITS DECORATION. THE MACHINE'S OWN SIGHT.
 * One rectangle at the capture aspect the briefing states, 1920 by 1080, appears on five frames
 * and does nothing but change size and count. 7.8 m lying empty across the lane (1). 0.42 m as
 * the housing's own field (2). Eight small hollow marks on one sound house, one per condition
 * the briefing says the software detects (3). 1.2 m closed tight on one patch of roof flashing
 * (8). Empty again on a committee room screen (9). It opens on a street, learns eight words,
 * closes on a patch, and lands in a room where nothing has been decided. Its aspect is never
 * typed, it is computed from the figure, so a frame that got the resolution wrong draws the
 * wrong shape rather than quietly printing a 16 by 9 somebody remembered.
 *
 * THE ACCENT LAW, AND IT IS THE STRICTEST THING IN THIS FILE.
 *
 *     BLUEBONNET IS THE MACHINE'S SIGHT. PAPER IS THE CITY'S LANGUAGE. THEY NEVER TOUCH.
 *
 * #4E5FA8 lands ONLY on the capture rectangle, its corner brackets and its detection marks, on
 * frames 1, 2, 3, 8 and 9. It never touches a drawn page, a line of type, a numeral, a mark in
 * a count field or anything a person in this world wrote. Frames 4, 5, 6 and 7 are the paper
 * frames and they carry NONE AT ALL. Frame 4's absence is the load bearing one, because on
 * December 9th nothing had been detected yet. A reader who swipes twice has the code without
 * being told it, and the deck's argument is that these two things are separate and the city's
 * trouble is entirely on the paper side.
 *
 * THE COUNT FIELD CARRIES NO ACCENT, AND THAT IS A REFUSAL RATHER THAN A CHOICE. Frame 5 draws
 * 39 of the 57 citations filled. Painting the filled marks in the machine's own colour would be
 * the drawing asserting that the machine put them there, and the record establishes where the
 * citations landed and nothing whatever about cause. Two people disagree about why in their own
 * words on that frame, at the same size, and the ink is the same for both.
 *
 * AND AN ACCENT UNDER THE FLOOR IS AN ACCENT THAT IS NOT THERE. layout_check measures coverage
 * at 432 px against 0.2 percent of the frame. A 1.2 m rectangle at Z 11 is about 96 px wide and
 * an 8 px stroke alone does not clear it, so frame 8 carries four corner brackets and one solid
 * tick as well. A frame either carries the colour where a reader can find it or declares none,
 * and the deck has five either way, which is inside the band of three to six.
 *
 * THE RESERVED RED IS NOT SPENT, DELIBERATELY. The one dated thing in this story is a committee
 * briefing on October 19th, which is a door a reader may walk through and not a window closing
 * on them. `signal_soon` #BF0A30 means a deadline inside a week and nothing else on this project
 * wears it. Spending the urgent colour on a date that asks nothing would be the courtesy
 * notice's own move committed in this deck's ink, and the deck's whole argument is about a
 * document that implies an obligation it does not carry.
 *
 * THE MUTE WORLD LAW, AND IT IS WHAT KEEPS A DOCUMENT DECK FROM BEING NINE RECTANGLES.
 *
 *     PAPER IS THE ONLY THING IN THIS DECK THAT CARRIES GLYPHS.
 *
 * No truck livery, no door decal, no street sign, no house number, no badge, no name plate, no
 * screen text, no label on any object in nine frames. The world is mute and the paper talks. It
 * is also why no drawn building can be read as one real property, which matters because the
 * record names an Oak Cliff homeowner and gives no address.
 *
 * THE CONDITION LAW, AND IT IS STATED AS A COUNT SO A CRITIC CAN CHECK IT.
 *
 *     NOT ONE OF THE EIGHT DETECTED CONDITIONS IS DRAWN ON ANY HOUSE IN NINE FRAMES.
 *
 * No high grass, no boarded window, no graffiti, no tire, no collapsing structure, no illegal
 * dumping, no trash. The eight exist in exactly one place in this deck, as eight lines of mono
 * type on frame 3, and never as a drawn defect anywhere. The one thing at a curb is an ordinary
 * set-out squared to the kerb line on the week the truck comes for it, which is what the record
 * says the truck is there for. No sagging gutter, no peeling paint, no dead lawn, no broken
 * step. A drawn slum would be this deck publishing a finding nobody measured, and it would make
 * the machine right.
 *
 * THE ONE THING A CAMERA REPORTED IS DRAWN AND IT IS NOT A DEFECT. A camera flagged what it took
 * to be a temporary repair on a roof its owner says is permanent flashing (c31). Frame 8 draws
 * galvanized step flashing, sound, lying correctly, with the machine's rectangle closed on it.
 *
 * NO TWO QUANTITIES EVER TOUCH. There is exactly ONE mark field in nine frames, on frame 5, and
 * it is one scale, one object class and one pitch. 21,000, 10,000, 3,700 and about 300 come from
 * three sources measuring different things over different windows, so they NEVER APPEAR AS
 * GEOMETRY AT ALL. They are numerals in copy on the frames they belong to and nothing draws
 * them, which is a stronger discipline than drawing them apart and hoping a reader does not join
 * them. Nothing anywhere is nested, chained, stacked, bracketed or arrowed into anything else.
 * The single containment this deck may draw is the one the memo itself states, which is 39 of
 * the 57 (c27), and it is drawn once.
 *
 * AND THE REMAINDER IS NEVER NAMED. 57 marks are stamped and 39 are filled. The count of the
 * rest is a subtraction this deck does not perform and no numeral for it appears in any frame,
 * any label, any dek or any file, because the memo says nothing whatever about them.
 *
 * NOTHING IS DRAWN THAT HAS NOT HAPPENED. Frame 9's committee room is empty, no briefer is
 * depicted, and the rectangle on its screen carries nothing.
 *
 * THE FRAMES DRAW IN GREYS. Every scene is drawn into TXINK's offscreen twin in greys and the
 * print maps tone to ink on the deck's stock. That is why this file hands out a GREY SCALE
 * rather than a colour ramp: a frame that picks its own colours has left the deck. The one place
 * real colour is painted is `over`, where the accent and the type reserve go, after the screen
 * has run.
 */
(function (global) {
  "use strict";

  if (!global.TXDECK) throw new Error("oakcliff.js needs txdeck.js loaded first");

  /* ONE DECLARATION, AND IT IS THE ONLY ONE IN THE DECK. Nine frames can't hold nine lights. */
  TXDECK.declare({
    world: "oakcliff",
    light: { az: 38, el: 22, keyToFill: 4.6 },
    ground: "#222E16",
    material: "#D9DEC9",
    accent: "#4E5FA8",
    grade: {
      exposure: -0.010,
      saturation: 1.04,
      contrast: 1.15,
      filmic: true,
      lift: [0.014, 0.019, 0.012],   /* shadows toward the turf's own green rather than to blue */
      gain: [1.042, 1.020, 0.958],   /* highlights to a low September sun, warm on a cool ground */
      vignette: 0.20,
      bloom: { threshold: 0.82, strength: 0.20, radius: 8 },
      /* GRAIN AT 0.014, FOLLOWING THE SEPTEMBER 19TH MEASUREMENT RATHER THAN THE HOUSE 0.044.
       * That run measured its vector PDF at 68.7 MB against 6 to 14 MB for every deck before it,
       * tested three hypotheses, and found that cutting per pixel noise and the dither was worth
       * 9 MB while a raised screen floor and a higher gamma were worth nothing. September 20th
       * then measured 61.95 MB on a hatch and concluded the screen is not the lever either. So
       * this is carried forward as the one knob known to move, and the size is DISCLOSED rather
       * than predicted. A number in this file that was guessed is worse than no number. */
      grain: { amount: 0.014, size: 3, seed: 20260921 },
      aberration: 0,
      dither: false,
      sharpen: 0.30
    }
  });

  var N = {};
  N.W = 1080;
  N.H = 1350;

  /* ------------------------------------------------------------------- stock
   *
   * The paper and the ink, once, for all nine frames. A screen is the deck's STOCK and changing
   * stock between frames is a different print job rather than variety.
   */
  N.GROUND = "#222E16";   /* St. Augustine in live oak shade. Item eight on the detection list */
  N.INK    = "#D9DEC9";   /* chalked city fleet body panel, the deck's paper */
  N.ACCENT = "#4E5FA8";   /* bluebonnet. THE MACHINE'S SIGHT, and nothing else wears it */
  N.DEK    = "#AEB6A0";
  N.RULE   = "#8F9683";   /* the furniture, one pale ink on all nine frames */

  /* THE TWO MATERIALS, AND THE BOUNDARY BETWEEN THEM IS THE STORY.
   * `STOCK` is laser bond lying in morning shade and it is deliberately NOT white: four cream
   * sheets at full white made September 18th's canvas mean strobe, and the judges converged on
   * capping unscreened stock rather than on dimming it afterwards. `TONER` is fused laser toner
   * on that bond. Every glyph in the drawn world is one of these two and there are no others. */
  N.STOCK  = "#C8BE9B";
  N.TONER  = "#151409";

  N.GUMBO    = "#2A2620";  /* Blackland Prairie clay in the alley */
  N.ASPHALT  = "#1B1E1A";
  N.SHINGLE  = "#3A3129";  /* three tab asphalt shingle */
  N.BRICK    = "#6E4736";  /* Oak Cliff bungalow common brick */
  N.FLASHING = "#9AA0A0";  /* galvanized flashing. The temporary repair itself */

  /* STIPPLE, CELL 5, ON ALL NINE, AND BOTH NUMBERS ARE PROBE FRAME DECISIONS RATHER THAN TASTE.
   *
   * A STIPPLE is the tooth of both a lawn and laser toner, which are the deck's two materials, so
   * the stock rhymes with what is being printed. It is also NOT the last two decks' screens,
   * halftone at cell 7 on September 19th and hatch at cell 6 on September 20th.
   *
   * A STIPPLE'S WHITE FIELD CEILING ON THIS GROUND IS NOT KNOWN AND IS NOT GUESSED HERE. Phase
   * 10.5 prints a white field through THIS configuration on the probe frame and records the
   * ceiling BEFORE the value arc is committed. The arc is written against the press. The press is
   * never chased to the arc, which is September 15th's lesson and carousel no. 25 paid for it.
   * The stated fallback is hatch at cell 7, deliberately not cell 6, which shipped yesterday.
   */
  N.SCREEN = { mode: "stipple", cell: 5, angle: 0, gamma: 1.18, floor: 0.05 };
  N.EDGES  = { threshold: 18, width: 1.3, alpha: 0.78, dx: -1.1, dy: 0.6 };

  /* THE GREY SCALE THE TWIN IS DRAWN IN, dark to light. A frame reaches for these by name so nine
   * frames can't each invent their own tonal separation. The gap in the middle is deliberate:
   * nothing contrasts against a mid tone, so objects are separated ACROSS the hole rather than
   * inside it. `mid` is terrain only, and a subject drawn at `mid` against the ground is the
   * defect that lesson names. */
  N.G = {
    voidd:  "#000000",   /* the deepest dark. A truck body interior, a doorway seen from outside */
    deep:   "#111410",   /* the deck's own shade, under an eave, under a live oak */
    dark:   "#22261E",   /* a left face, the deck's dark side */
    shade:  "#383C30",   /* asphalt in shadow, the shaded half of a sheet */
    mid:    "#5A5E4E",   /* NOT for a subject against the ground. Turf and terrain only */
    stone:  "#7C806E",   /* concrete, a brick face in shade, a lit parkway strip */
    metal:  "#A4A89A",   /* a chalked fleet panel, galvanized flashing, a lit flank */
    bright: "#CFD2BE",   /* a lit face taking the key square on, bond in the light */
    glare:  "#F0F2E0"    /* the sun square on a windscreen or a chrome mirror arm. Sparingly */
  };

  /* --------------------------------------------------------------------- ramp
   * One ramp, off the deck's material, for the few marks painted in real colour in `over`.
   * The print path does not use it and most frames never call it.
   *
   * TXDECK.pick TAKES AN INDEX, NOT A FRACTION, and this is the fastest way to draw a faded
   * frame by accident. pick(ramp, 0.74) written by an author who meant "74 percent up the ramp"
   * returns step 1 of 9. Write integer steps and read them as steps.
   */
  N.RAMP = TXDECK.ramp(9, { Lmin: 0.05, Lmax: 0.86, ambientHue: 122, drift: 12 });
  N.pick = function (i) { return TXDECK.pick(N.RAMP, i); };

  /* -------------------------------------------------------------------- scene
   *
   * A TXSCENE carrying THIS DECK'S light, so a frame can't set up a camera lit from anywhere
   * else. Standing eye on the parkway strip is 1.63 m and that is the deck's default, because a
   * person standing at the curb is the reader's position in this story.
   *
   * EVERY OPTION ON THE BENCH IS OPTIONAL AND A WRONG NAME IS SILENTLY A DEFAULT. `S.strip`
   * takes X, w, near, far, fill. `S.gridX` takes X extents in from/to and Z extents in
   * near/far, and `S.gridZ` takes Z extents in from/to, and they are NOT the same shape. Read
   * the signature in txscene.js before the call, then look at the render.
   */
  N.scene = function (a, o) {
    if (!global.TXSCENE) throw new Error("oakcliff.scene needs txscene.js on this frame");
    o = o || {};
    var d = TXDECK.deck();
    return TXSCENE.create(a, {
      w: N.W, h: N.H,
      eye:     o.eye     == null ? 1.63 : o.eye,
      horizon: o.horizon == null ? 760  : o.horizon,
      f:       o.f       == null ? 900  : o.f,
      sky:     o.sky     || N.G.deep,
      fogZ:    o.fogZ    == null ? 1e9 : o.fogZ,
      light:   { az: d.light.az, el: d.light.el }
    });
  };

  /* -------------------------------------------------------------------- print
   *
   * THE DECK'S STOCK, HANDED TO A FRAME. A frame passes its own `draw` and its own `over` and
   * gets the deck's paper, ink, screen and contour.
   *
   * There is no drawFrame here and there never will be. A shared draw-the-whole-slide is a
   * template, deck_chassis.py refuses one by name, and the per frame composition is this
   * machine's whole strength. The chassis hands a frame the press. The frame decides what goes
   * through it.
   */
  N.print = function (cx, o) {
    if (!global.TXINK) throw new Error("oakcliff.print needs txink.js on this frame");
    o = o || {};
    TXINK.print(cx, {
      w: N.W, h: N.H,
      ground: o.ground || N.GROUND,
      ink:    o.ink    || N.INK,
      fibre:  o.fibre  == null ? 0.05 : o.fibre,
      screen: o.screen || N.SCREEN,
      edges:  o.edges  || N.EDGES,
      seed:   o.seed   == null ? 31 : o.seed,
      draw:   o.draw,
      over:   o.over
    });
  };

  /* ------------------------------------------------------------ world primitives
   *
   * The few shapes more than one frame needs, handed out as PARTS. Each is drawn in metres on a
   * scene, never in screen pixels, so frame 1's porch boards and frame 5's porch boards are the
   * same surface seen twice rather than two drawings that resemble each other.
   */

  /* THE CAPTURE RECTANGLE. THE DECK'S MOTIF, AND ITS ASPECT IS COMPUTED RATHER THAN TYPED.
   * `aspect` is handed in from figures.json's hardware.resolution, parsed by the frame, so a
   * frame that got the resolution wrong draws a rectangle of the wrong shape rather than
   * quietly printing a 16 by 9 somebody remembered. Painted in `over`, in flat accent, after
   * the screen has run, because the machine's sight is never screened into the world's tooth.
   *
   * `brackets` adds four corner Ls and one solid tick. It exists for frame 7, where the
   * rectangle is 1.2 m wide and an 8 px stroke alone measures under layout_check's 0.2 percent
   * floor at 432 px. A colour spent below the floor costs the deck its scarcity and buys a
   * reader nothing. */
  N.captureRect = function (c, r, o) {
    o = o || {};
    var lw = o.width == null ? 8 : o.width;
    c.save();
    c.strokeStyle = o.ink || N.ACCENT;
    c.lineWidth = lw;
    c.lineJoin = "miter";
    c.strokeRect(r.x, r.y, r.w, r.h);
    if (o.brackets) {
      var b = o.bracket == null ? Math.max(28, Math.min(r.w, r.h) * 0.34) : o.bracket;
      c.lineWidth = lw * 2.1;
      var corners = [[r.x, r.y, 1, 1], [r.x + r.w, r.y, -1, 1],
                     [r.x, r.y + r.h, 1, -1], [r.x + r.w, r.y + r.h, -1, -1]];
      for (var i = 0; i < corners.length; i++) {
        var q = corners[i];
        c.beginPath();
        c.moveTo(q[0] + q[2] * b, q[1]);
        c.lineTo(q[0], q[1]);
        c.lineTo(q[0], q[1] + q[3] * b);
        c.stroke();
      }
      /* one solid tick, so the shape survives a 432 px downsample that eats a hairline */
      c.fillStyle = o.ink || N.ACCENT;
      c.fillRect(r.x + r.w * 0.5 - b * 0.5, r.y + r.h + lw * 1.2, b, lw * 2.4);
    }
    c.restore();
    return r;
  };

  /* A SHEET OF LASER BOND, DRAWN IN METRES ON A SURFACE, WITH ITS OWN CAST AND ITS OWN CURL.
   * US Letter is 0.216 by 0.279 m and both orientations are real. `curl` is the near corner's
   * lift in metres, and the shadow it throws BACK ONTO ITS OWN PAGE is what makes a drawn sheet
   * a physical object rather than a rectangle of a lighter grey. Returns the page's screen rect
   * so a frame can mount its type on it. */
  N.sheet = function (a, S, o) {
    o = o || {};
    var wM = o.wM == null ? 0.216 : o.wM, hM = o.hM == null ? 0.279 : o.hM;
    var X = o.X == null ? 0 : o.X, Z = o.Z == null ? 0.8 : o.Z, Y = o.Y == null ? 0 : o.Y;
    var ppm = S.ppm(Z);
    var w = wM * ppm, h = hM * ppm;
    var p = S.project(X, Y, Z);
    var r = { x: p.x - w / 2, y: p.y - h * (o.anchor == null ? 0.5 : o.anchor), w: w, h: h };
    var tilt = (o.tilt == null ? 0 : o.tilt) * Math.PI / 180;
    var dir = TXDECK.castDir();

    a.save();
    a.translate(r.x + r.w / 2, r.y + r.h / 2);
    a.rotate(tilt);
    a.translate(-(r.x + r.w / 2), -(r.y + r.h / 2));

    /* THE CAST FIRST, so the page sits on the surface rather than over its own shadow. A sheet
     * lying flat casts a short offset rather than a long one, because its own height above the
     * surface is a millimetre or two and not its width. */
    var off = Math.max(3, h * 0.012);
    a.fillStyle = "rgba(0,0,0,0.42)";
    a.fillRect(r.x + dir[0] * off, r.y + dir[1] * off, r.w, r.h);

    a.fillStyle = o.stock || N.G.bright;
    a.fillRect(r.x, r.y, r.w, r.h);

    /* THE CURLED NEAR CORNER AND ITS SHADOW ON ITSELF. Drawn only when asked for, because a
     * curl on every sheet in the deck would be a mannerism rather than an observation. */
    if (o.curl) {
      var cm = o.curl * ppm;
      var cxn = r.x, cyn = r.y + r.h;                      /* the near left corner */
      a.beginPath();
      a.moveTo(cxn, cyn); a.lineTo(cxn + cm * 2.1, cyn); a.lineTo(cxn, cyn - cm * 2.1);
      a.closePath();
      a.fillStyle = "rgba(0,0,0,0.30)";                    /* the shadow the lift throws back */
      a.fill();
      a.beginPath();
      a.moveTo(cxn + cm * 0.5, cyn - cm * 0.5);
      a.lineTo(cxn + cm * 2.1, cyn - cm * 0.2);
      a.lineTo(cxn + cm * 0.2, cyn - cm * 2.1);
      a.closePath();
      a.fillStyle = o.stock || N.G.bright;                 /* the lifted underside, still lit */
      a.fill();
    }
    a.restore();
    return r;
  };

  /* PORCH BOARDS AT A TRUE 140 mm TONGUE AND GROOVE. Frames 5 and 6 stand on the same porch, so
   * the boards are one construction called twice rather than two drawings that resemble each
   * other. `ppm` is pixels per metre at the surface's distance, from the scene, so the board
   * pitch is the frame's own ruler rather than a texture at an invented pitch. */
  N.porchBoards = function (a, r, ppm, o) {
    o = o || {};
    var pitch = 0.140 * ppm;
    a.save();
    a.beginPath(); a.rect(r.x, r.y, r.w, r.h); a.clip();
    a.fillStyle = o.face || N.G.shade;
    a.fillRect(r.x, r.y, r.w, r.h);
    a.strokeStyle = o.joint || N.G.deep;
    a.lineWidth = Math.max(1, pitch * 0.05);
    for (var y = r.y; y <= r.y + r.h + pitch; y += pitch) {
      a.globalAlpha = 0.66;
      a.beginPath(); a.moveTo(r.x, y); a.lineTo(r.x + r.w, y); a.stroke();
      /* the lit shoulder of each board, on the key's own side */
      a.globalAlpha = 0.20;
      a.strokeStyle = N.G.metal;
      a.beginPath(); a.moveTo(r.x, y + pitch * 0.09); a.lineTo(r.x + r.w, y + pitch * 0.09);
      a.stroke();
      a.strokeStyle = o.joint || N.G.deep;
    }
    a.globalAlpha = 1;
    a.restore();
  };

  /* THE CAST, COMPUTED. Every shadow in nine frames asks this rather than guessing, which is what
   * makes them agree. At el 22 a cast is 2.48 times the object's height. */
  N.cast    = function (metres) { return TXDECK.castLen(metres); };
  N.castDir = function () { return TXDECK.castDir(); };

  /* THE TYPE RESERVE, AND THE DECK HAS TWO KINDS OF IT.
   *
   * A frame has light-on-dark type (the hook, the dek, the furniture) which needs the light
   * DIMMED toward it or the wash eats the contrast, and it can also have dark-on-light type
   * printed ON a drawn page, which NEEDS the light and is destroyed by punching the pool away
   * from it. One reserve list for both is wrong twice, so a frame carrying a drawn page keeps
   * two and reserves BOTH from drawn edges, because a rule through a glyph is a strike whichever
   * way the values run.
   *
   * A HOLE PUNCHED IN A LIGHT LAYER IS A PLATE WITH THE SIGN FLIPPED. Light DIMS toward type. It
   * is not removed from around it. Soft, partial, and a wide feather.
   */
  N.reserve = function (c, o) {
    o = o || {};
    TXINK.reserve(c, {
      ground: N.GROUND,
      top: o.top == null ? 0 : o.top,
      topSolid: o.topSolid == null ? 0 : o.topSolid,
      bottom: o.bottom == null ? 190 : o.bottom,
      bottomSolid: o.bottomSolid == null ? 118 : o.bottomSolid
    });
  };

  /* THE LINE BOXES AND THE MASK, ASKED FOR ONCE. A frame fits its type FIRST, then measures, then
   * hands the geometry to the art, which is the order that makes a reserve live geometry rather
   * than a guess. An element repositioned after this was never measured, and deck_chassis.py
   * refuses that by name. */
  N.boxes = function (sel, pad) {
    return TXDECK.lineBoxes(sel || ".hook, .dek, .kick, .count, .src, .tx-site",
                            pad == null ? 18 : pad);
  };
  N.mask = function (boxes, feather) {
    return TXDECK.reserveMask(boxes, feather == null ? 28 : feather);
  };

  /* QUIET THE ART BEHIND A LINE OF TYPE, AND IT IS A WASH RATHER THAN A PLATE.
   *
   * Nine frames of this deck are drawn worlds with real horizontal geometry in them: a porch
   * board at a true 0.140 m, a curb line, the cut edge of a sheet, a dais front. Every one of
   * those is a full width edge, and wherever one crosses a glyph band the QA harness reads it as
   * a strikethrough, correctly, because at feed width that is what it looks like. Moving nine
   * pieces of true geometry to dodge the furniture would be drawing the world around the type,
   * which is backwards.
   *
   * SO THE LIGHT DIMS TOWARD THE TYPE. A soft falloff over each measured line box, in the deck's
   * own ground, capped at 0.44 alpha and feathered over the full height of the box again above
   * and below it. deck_chassis.py fails the build on any fill over 0.55 behind display type, and
   * this is deliberately well under it.
   *
   * It runs BEFORE TXDECK.punch, which dims the screen, so the two compose rather than fight.
   */
  N.quiet = function (c, boxes, alpha) {
    if (!boxes || !boxes.length) return;
    var A = alpha == null ? 0.44 : Math.min(0.52, alpha);
    var g = [parseInt(N.GROUND.slice(1, 3), 16),
             parseInt(N.GROUND.slice(3, 5), 16),
             parseInt(N.GROUND.slice(5, 7), 16)];
    c.save();
    for (var i = 0; i < boxes.length; i++) {
      var b = boxes[i], fe = b.h;
      var grad = c.createLinearGradient(0, b.y - fe, 0, b.y + b.h + fe);
      grad.addColorStop(0.00, "rgba(" + g[0] + "," + g[1] + "," + g[2] + ",0)");
      grad.addColorStop(0.30, "rgba(" + g[0] + "," + g[1] + "," + g[2] + "," + A + ")");
      grad.addColorStop(0.70, "rgba(" + g[0] + "," + g[1] + "," + g[2] + "," + A + ")");
      grad.addColorStop(1.00, "rgba(" + g[0] + "," + g[1] + "," + g[2] + ",0)");
      c.fillStyle = grad;
      c.fillRect(0, b.y - fe, N.W, b.h + fe * 2);
    }
    c.restore();
  };

  /* FLAT STOCK LAID UNDER A BLOCK OF DARK ON LIGHT TYPE, MEASURED OFF THE TYPE IT SERVES.
   *
   * September 20th paid for this twice. Type painted in the `over` pass is flat and unscreened,
   * which a document frame does from the start. It is the SHEET UNDER IT that carries the screen,
   * and a stipple under small mono fills the counters, so three judges reported a screen running
   * through glyphs it never touched. This lays unscreened stock under the block and nothing
   * wider, because spanning it across the whole sheet prints a filled bar.
   *
   * `pad` is in px. The rect is returned so the caller can place the type against it rather than
   * measuring twice.
   */
  N.stock = function (c, r, o) {
    o = o || {};
    var pad = o.pad == null ? 10 : o.pad;
    c.save();
    c.fillStyle = o.stock || N.STOCK;
    c.fillRect(r.x - pad, r.y - pad, r.w + pad * 2, r.h + pad * 2);
    c.restore();
    return { x: r.x - pad, y: r.y - pad, w: r.w + pad * 2, h: r.h + pad * 2 };
  };

  global.TXOC = N;
})(typeof window !== "undefined" ? window : globalThis);
