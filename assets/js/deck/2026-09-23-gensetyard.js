/* gensetyard.js — the chassis for carousel No. 32 (2026-09-23).
 *
 * WHAT THIS IS. The deck spends nine frames on one gas generation yard and the paper that
 * yard has to come to. Nine frames share one light, one stock and one way of seating type, and
 * this file is those three things and nothing else. Every frame's COMPOSITION is written per
 * frame.
 *
 * THE DECK'S ARGUMENT, AS IT SHIPPED. A permit halt scoped by WHO IS ASKING cannot be aligned
 * to an audit scoped by WHAT IS ADVANCING THROUGH THE INTERCONNECTION PROCESS, and a real West
 * Texas project already sits in the gap: 76 megawatts contracted behind the meter from about
 * forty reciprocating gas engines, which the audit's process never sees.
 *
 * THIS FILE SHIPPED A REFUTED ARGUMENT IN ITS OWN HEADER AND A SCORER CAUGHT IT. It read that
 * the deck argues from the AIR PERMIT, "the one state approval that follows engines rather than
 * wires", and it named the deck "THE DOOR THAT WAS ALWAYS THERE". That mechanism was the plan
 * and the fact check REFUTED it: the agency's guidance describes internal combustion engines as
 * the kind of facility found at sources needing New Source Review and says nothing about whether
 * or when a particular installation is one. The claim was cut from every published surface on
 * the day it failed, and this header, which is committed and merges to main, kept it. A file
 * the next run reads is not a comment. It is the premise it will start from.
 *
 * THE WORLD. A GAS GENERATION YARD ON A WEST TEXAS PAD AT TWENTY TO TEN AT NIGHT, LIT BY ITS
 * OWN MAST. Reciprocating gas sets in line on skids, their stacks going up out of the pool of
 * light into a sky with nothing in it, a switchgear house, a perimeter fence with a posted
 * notice wired to it. Inside that world, one interior the same fixture does not reach, which
 * is a counter where a permit is filed.
 *
 * WHY A YARD AT NIGHT. Because the argument is about machines a process never sees, and the
 * machines are the thing this deck can actually draw. It is not a claim about what any permit
 * regulates, and no frame makes one.
 *
 * THE LIGHT, IN WORDS A FRAME AUTHOR CAN CHECK A DRAWING AGAINST. THE KEY IS A YARD MAST,
 * HIGH AND OFF THE CAMERA'S LEFT SHOULDER, AT 28 DEGREES ABOVE THE PLANE. So every lit face
 * in this deck is a LEFT face, every right face is the deck's dark side, and every cast runs
 * DOWN AND TO THE RIGHT at 1.88 times the object's own height. A 1.7 m person throws about
 * 3.2 m. A 3.0 m genset skid throws about 5.6 m. A 12 m stack throws about 22.6 m and runs
 * off the pad. If a drawn object has no contact where it meets the ground, or a cast running
 * left, that frame is wrong and gets redrawn rather than tuned.
 *
 * WHY A MAST RATHER THAN A SUN. Across twenty one decks the judges' finding was flatness, and
 * a mast is the honest cure rather than a stylistic one. A local source has a FALLOFF, so the
 * pad is lit and the sky and the far fence are not, which gives the type its quiet by
 * construction instead of by a plate. It is also when these yards are actually watched, and
 * the one frame that carries daylight is the counter, which is the point being made.
 *
 * THE GROUND WAS MEASURED, NOT CHOSEN. #322C44 is a night sky over a sodium lit pad. Its
 * nearest neighbour among the shipped grounds this run could read is September 20th's #2E2016
 * at dE76 24.54, against a floor of 10, and its chroma is inside the band those grounds occupy
 * so it reads as paper rather than as a colour. The first two passes at this picked warm darks
 * by eye and both landed inside dE 3 of #2E2016. A palette checked only by eye is a palette
 * that repeats.
 *
 * THE FIGURE THAT STOOD HERE WAS 14.18 AND IT WAS WRONG, WHICH IS RECORDED RATHER THAN QUIETLY
 * CORRECTED. A scorer recomputed the distance to #2E2016 by hand, got about 26, and said the
 * chassis and the artwork ledger could not both be right. They were right to: the two numbers
 * disagreed and one of them was going to be inherited. 24.54 is what this run computes from the
 * two entries in the last six that carry a ground hex at all, which is the other half of the
 * finding and is worth stating rather than smoothing: FOUR of the last six shipped decks record
 * no ground colour, so "the last six" is a window this comparison cannot actually fill. The
 * claim is narrowed to what was measured.
 *
 * AND IT SAT TWO PARAGRAPHS FROM A PARAGRAPH CONGRATULATING THIS RUN FOR CATCHING THE SAME
 * DEFECT IN THE VALUE ARC. That is the whole reason it is written down.
 *
 * THE ACCENT LAW, AND IT IS THE STRICTEST THING IN THIS FILE.
 *
 *     AMBER IS THE STATE'S PAPER. STEEL IS THE MACHINERY. THEY NEVER TOUCH.
 *
 * #E0A33F lands ONLY on a permit, a posted notice, a docket number and the comment door. It
 * never touches an engine, a stack, a skid, a container, a fence rail or the pad. The frames
 * that carry the machinery carry NONE AT ALL, and a reader who swipes twice has the code
 * without being told it. The deck's whole argument is that these are two separate systems and
 * that only one of them ever had to answer for the other.
 *
 * THE RESERVED RED IS NOT SPENT, DELIBERATELY. `signal_soon` #BF0A30 means a deadline inside a
 * week and nothing else on this project wears it. The report back is October 19th, which is
 * further out than that. A line here once described an Abilene comment file's close date,
 * from a finding whose every element the fact check could not verify, and it is gone.
 * Spending the urgent colour on either would be this deck asserting an urgency the documents
 * do not carry.
 *
 * THE MUTE WORLD LAW, AND IT IS WHAT KEEPS AN INDUSTRIAL DECK FROM BEING NINE GREY BOXES.
 *
 *     PAPER IS THE ONLY THING IN THIS DECK THAT CARRIES GLYPHS.
 *
 * No manufacturer's plate on a genset, no door decal, no unit number stencilled on a skid, no
 * company name on the switchgear house, no sign at the gate. The world is mute and the paper
 * talks. It is also why no drawn yard can be read as one real facility, which matters because
 * the record names a permit number and a campus and gives no site plan.
 *
 * NOTHING IS DRAWN THAT HAS NOT HAPPENED. No permit is drawn refused, no stack is drawn
 * capped, no gate is drawn chained. The halt is an instruction to an agency about what it will
 * issue, and a drawing of a stopped construction site would publish a consequence nobody has
 * measured.
 *
 * THE FRAMES DRAW IN GREYS. Every scene is drawn into TXINK's offscreen twin in greys and the
 * print maps tone to ink on the deck's stock. That is why this file hands out a GREY SCALE
 * rather than a colour ramp. The one place real colour is painted is `over`, where the accent
 * and the type reserve go, after the screen has run.
 *
 * THE SCREEN IS A LINE SCREEN AT CELL 6, AND EVERY NUMBER IN IT WAS MEASURED RATHER THAN
 * GUESSED. A LINE screen is the banknote and the engineering sheet, which is what a permit
 * drawing is, and it is none of the last three decks' stocks: halftone at cell 7 on September
 * 19th, hatch at cell 6 on September 20th, stipple at cell 5 on September 21st.
 *
 * THE PRESS WAS PRINTED AND READ BEFORE THE VALUE ARC WAS COMMITTED. Phase 10.5 laid all nine
 * steps of N.G as full width bands through this exact configuration and read each band's L* off
 * the rendered PNG. The first pass, at cell 5 with gamma 0.5 and bloom at threshold 0.78
 * strength 0.26, printed a MONOTONIC scale spanning 64 L* and then COLLIDED AT THE TOP: `bright`
 * and `glare` both came out at 75.01, which is the ink's own value at full coverage, so the two
 * lightest steps of nine were the same colour. Note that `weight` does nothing in line mode,
 * which is why the first fix aimed at it would have been wasted: TXINK's line branch takes its
 * stroke width from `cell * 0.9 * d` and reads `o.weight` only for a hatch.
 *
 * Cell 6 opens the pitch, gamma 0.72 pulls the low end down off the floor, and bloom at
 * threshold 0.88 strength 0.14 stops the grade clipping the top. Measured on the second print:
 *
 *     step     twin L*   printed L*
 *     voidd        0.00        10.83
 *     deep         4.40        22.25
 *     dark        15.34        32.18
 *     shade       26.45        40.12
 *     mid         42.21        50.22
 *     stone       56.16        58.33
 *     metal       69.06        64.63
 *     bright      84.30        70.96
 *     glare       95.54        73.11
 *
 * Monotonic, spanning 62.28 L*, smallest step 2.15 and largest 11.43. **`glare` and `bright` are
 * only 2.15 L* apart and a frame may not rest a reading on telling them apart.** `glare` is
 * spent on specular hits alone. September 21st shipped a twin scale spanning 95 L* that printed
 * across nineteen and was not monotonic, and five critics read that deck as hairline wireframes
 * over noise. Nothing was wrong with any frame's drawing. Every frame was drawing through a
 * press with no tonal range.
 */
(function (global) {
  "use strict";

  if (!global.TXDECK) throw new Error("gensetyard.js needs txdeck.js loaded first");

  /* ONE DECLARATION, AND IT IS THE ONLY ONE IN THE DECK. Nine frames can't hold nine lights. */
  TXDECK.declare({
    world: "gensetyard",
    light: { az: -48, el: 28, keyToFill: 6.2 },
    ground: "#322C44",
    material: "#CFD2D8",
    accent: "#E0A33F",
    grade: {
      exposure: -0.008,
      saturation: 1.02,
      contrast: 1.18,
      filmic: true,
      /* shadows toward the sky's own violet rather than to blue, highlights to a cool
       * discharge lamp rather than to a warm sun. A mast is not a sunset. */
      lift: [0.016, 0.012, 0.022],
      gain: [0.982, 1.006, 1.038],
      vignette: 0.24,
      bloom: { threshold: 0.88, strength: 0.14, radius: 10 },
      /* GRAIN AT 0.014, CARRIED FORWARD FROM THE SEPTEMBER 19TH MEASUREMENT rather than the
       * house 0.044. That run measured its vector PDF at 68.7 MB against 6 to 14 MB for every
       * deck before it, tested three hypotheses, and found cutting per pixel noise and the
       * dither was worth 9 MB while a raised screen floor and a higher gamma were worth
       * nothing. September 20th then measured 61.95 MB on a hatch and concluded the screen is
       * not the lever either. So this is the one knob known to move, and the size is
       * DISCLOSED rather than predicted. A number in this file that was guessed is worse than
       * no number. */
      grain: { amount: 0.014, size: 3, seed: 20260923 },
      aberration: 0,
      dither: false,
      sharpen: 0.32
    }
  });

  var N = {};
  N.W = 1080;
  N.H = 1350;
  N.SEED = 20260923;

  /* ------------------------------------------------------------------- stock
   *
   * The paper and the ink, once, for all nine frames. A screen is the deck's STOCK and
   * changing stock between frames is a different print job rather than variety.
   */
  N.GROUND = "#322C44";   /* night sky over a mast lit pad. Measured, see the header */
  N.INK    = "#CFD2D8";   /* galvanised steel under a discharge lamp, the deck's paper */
  N.ACCENT = "#E0A33F";   /* posted notice amber. THE STATE'S PAPER, and nothing else wears it */

  /* THE ACCENT IS PAINTED PRE COMPENSATED, AND THE NUMBER WAS MEASURED RATHER THAN GUESSED.
   * `over` runs before TXDECK.finish, so the grade moves whatever is painted there. Painting
   * N.ACCENT straight rendered as (181, 152, 52), which is dE76 15.85 from the declared hex
   * against layout_check's allowance of 12, and the gate reported the accent present on ZERO
   * frames while a reader could plainly see it. The transfer was then measured a SECOND time off a real
   * painted swatch rather than off a shadowed corner of one, which is what the first pass got
   * wrong: green came back at 204 against a target of 163. This is the colour that LANDS on
   * #E0A33F through this deck's grade.
   * A frame paints N.ACCENT_PAINT. Nothing paints N.ACCENT. */
  N.ACCENT_PAINT = "#F98C4A";
  N.DEK    = "#A7A6B4";
  N.RULE   = "#8A8798";   /* the furniture, one pale ink on all nine frames */

  /* THE TWO MATERIALS, AND THE BOUNDARY BETWEEN THEM IS THE STORY.
   * `STEEL` is a painted genset enclosure and a galvanised stack under mast light. `BOND` is
   * the agency's own paper, which is deliberately NOT white: four cream sheets at full white
   * made September 18th's canvas mean strobe, and the judges converged on capping unscreened
   * stock rather than dimming it afterwards. Every glyph in the drawn world sits on BOND. */
  N.STEEL = "#8E939B";
  N.BOND  = "#C6C0AA";
  N.TONER = "#141318";

  N.CALICHE  = "#5A5140";  /* compacted pad, warm against the sky */
  N.GRAVEL   = "#3E3A38";
  N.STACKTOP = "#9AA0A4";  /* galvanised flue. The deck draws it because it is what a gas
                            set LOOKS like, not because any verified claim says what a permit
                            regulates. See the header. */
  N.DARKSTEEL= "#4A4E56";

  /* THE GREY SCALE THE FRAMES DRAW IN, nine steps, dark to light. A frame that picks its own
   * colours has left the deck. These are TWIN values: the print maps them onto the stock. */
  N.G = {
    voidd:  "#000000",
    deep:   "#0F0F12",
    dark:   "#26262B",
    shade:  "#3E3E45",
    mid:    "#63636B",
    stone:  "#86868E",
    metal:  "#A8A8AF",
    bright: "#D2D2D6",
    glare:  "#F2F2F4"
  };
  N.STEPS = ["voidd", "deep", "dark", "shade", "mid", "stone", "metal", "bright", "glare"];

  /* THE PRESS. One stock for nine frames, and every number in it was read off a print.
   * See the measured nine step scale in this file's header. Do not change one of these without
   * re-printing the probe, because the value arc in the storyboard is written against THIS
   * press and a frame median is a claim about what comes out the other side. */
  N.SCREEN = { mode: "line", cell: 6, angle: 68, gamma: 0.72, floor: 0.02 };
  N.EDGES  = { threshold: 18, width: 1.3, alpha: 0.78, dx: -0.9, dy: 0.8 };

  /* ------------------------------------------------------------------ helpers
   *
   * PRIMITIVES, NOT A DRAWING. There is no drawFrame() in this file and there never will be.
   * A shared draw-the-whole-slide is a template, `deck_chassis.py` refuses one by name, and
   * the per frame composition is this machine's whole strength. What follows is the yard's
   * vocabulary. Each frame decides what to build from it.
   */

  /* The mast's pool on the pad. Takes x and y, in SCREEN px, and a reserve mask.
   * It does NOT take cx, cy or a rect list. Passing the wrong keys makes the gradient NaN and
   * paints the whole pool at the ORIGIN, which put a warm glow over the kicker on three frames
   * of the September 20th reference build and was reported three hundred pixels from its
   * cause. */
  N.pool = function (cx, o) {
    o = o || {};
    var x = o.x == null ? N.W * 0.30 : o.x;
    var y = o.y == null ? N.H * 0.62 : o.y;
    var r = o.r == null ? 760 : o.r;
    var peak = o.peak == null ? 0.90 : o.peak;
    var g = cx.createRadialGradient(x, y, 0, x, y, r);
    g.addColorStop(0.00, "rgba(255,255,255," + peak + ")");
    g.addColorStop(0.34, "rgba(255,255,255," + (peak * 0.44) + ")");
    g.addColorStop(0.68, "rgba(255,255,255," + (peak * 0.12) + ")");
    g.addColorStop(1.00, "rgba(255,255,255,0)");
    cx.save();
    cx.globalCompositeOperation = "lighter";
    cx.fillStyle = g;
    cx.fillRect(0, 0, N.W, N.H);
    cx.restore();
    /* LIGHT DIMS TOWARD TYPE. IT IS NOT REMOVED FROM AROUND IT. A hole punched at full
     * strength is a plate with the sign flipped, and it put a visible dark rounded rect behind
     * the site line on the first chassis deck. Soft, partial, wide feather. */
    if (o.reserve) N.dim(cx, o.reserve, o.dim == null ? 0.42 : o.dim);
  };

  /* Dim a light layer toward the type, partially, with a wide feather. */
  N.dim = function (cx, mask, amount) {
    var im = cx.getImageData(0, 0, N.W, N.H), d = im.data;
    for (var y = 0; y < N.H; y += 1) {
      for (var x = 0; x < N.W; x += 1) {
        var m = mask(x, y);
        if (m <= 0) continue;
        var k = 1 - amount * m;
        var i = (y * N.W + x) * 4;
        d[i] *= k; d[i + 1] *= k; d[i + 2] *= k;
      }
    }
    cx.putImageData(im, 0, 0);
  };

  /* A reciprocating gas set on a skid, drawn in METRES as a TXSCENE SPRITE.
   *
   * Not in the catalogue, so it is built from parts and goes in the backlog as a proposal.
   * Real machines of this class sit about 2.9 m to 3.2 m to the enclosure roof on a skid and the
   * flue runs well above that. Nothing here is a slab.
   *
   * THE PART KEY IS `type` AND NOT `kind`, AND THE SPRITE IS AN OBJECT AND NOT AN ARRAY.
   * TXSCENE's drawPart branches on `part.type` and silently draws nothing for anything else, and
   * S.spriteBox reads `sprite.w` and `sprite.h` off the sprite rather than off the parts. Both
   * mistakes render clean and produce an empty frame, which the near-uniform canvas gate is the
   * only thing that would catch.
   *
   * FILLS ARE NAMED, NEVER HEX. `ink`, `paper` and `accent` are resolved against the `inks` the
   * frame passes, so S.fade can walk them toward the sky with depth. A hex written here would be
   * a frame that does not fade, sitting in a row of frames that do.
   */
  N.genset = function (o) {
    o = o || {};
    var L = o.len == null ? 12.2 : o.len;      /* a 40 foot skid */
    var H = o.h == null ? 3.0 : o.h;           /* enclosure roof */
    var S = o.stack == null ? 11.5 : o.stack;  /* flue above grade */
    return {
      w: L, h: S,
      parts: [
        /* skid */
        { type: "rect", x: -L / 2, y: 0, w: L, h: 0.35, fill: "ink" },
        /* enclosure body */
        { type: "rect", x: -L / 2 + 0.2, y: 0.35, w: L - 0.4, h: H - 0.57, fill: "paper" },
        /* roof band, a shade lighter so the top edge reads */
        { type: "rect", x: -L / 2 + 0.2, y: H - 0.22, w: L - 0.4, h: 0.22, fill: "accent" },
        /* louvre bank at the radiator end */
        { type: "rect", x: L / 2 - 2.8, y: 0.7, w: 2.2, h: H - 1.3, fill: "ink" },
        /* THE STACK, because it is what a gas set looks like. The deck asserts nothing
         * about what any permit regulates and no frame does either. */
        { type: "rect", x: -L / 2 + 2.1, y: H, w: 0.62, h: S - H, fill: "paper" },
        { type: "rect", x: -L / 2 + 1.85, y: S - 0.5, w: 1.12, h: 0.30, fill: "accent" }
      ]
    };
  };

  /* A run of chain link with a top rail, between two ground points, in metres.
   *
   * TXSCENE EXPOSES ITS CONTEXT AS `S.ctx` AND NOT `S.cx`, AND `S.project` RETURNS AN ARRAY
   * [x, y] AND NOT AN OBJECT. The first cut of this helper got both wrong, which threw on the
   * first call rather than drawing quietly, and that is the better of the two failure modes:
   * the projection mistake inside a frame renders clean and produces nothing.
   */
  N.fence = function (S, a, b, o) {
    o = o || {};
    var c = S.ctx;
    var h = o.h == null ? 2.4 : o.h;
    var posts = o.posts == null ? 9 : o.posts;
    var i, t, X, Z, p0, p1;
    c.save();
    c.strokeStyle = o.ink || N.G.shade;
    c.lineWidth = o.w == null ? 2 : o.w;
    for (i = 0; i <= posts; i += 1) {
      t = i / posts;
      X = a[0] + (b[0] - a[0]) * t;
      Z = a[1] + (b[1] - a[1]) * t;
      p0 = S.project(X, 0, Z);
      p1 = S.project(X, h, Z);
      c.beginPath(); c.moveTo(p0[0], p0[1]); c.lineTo(p1[0], p1[1]); c.stroke();
    }
    p0 = S.project(a[0], h, a[1]); p1 = S.project(b[0], h, b[1]);
    c.beginPath(); c.moveTo(p0[0], p0[1]); c.lineTo(p1[0], p1[1]); c.stroke();
    c.restore();
  };

  /* A sheet of the agency's own bond, drawn on a surface, with its own ruled blocks.
   * The ONLY thing in this deck that may carry glyphs. */
  N.sheet = function (cx, r, o) {
    o = o || {};
    cx.save();
    cx.fillStyle = o.fill || N.G.bright;
    cx.fillRect(r.x, r.y, r.w, r.h);
    if (o.rules) {
      cx.strokeStyle = o.rule || N.G.mid;
      cx.lineWidth = o.rw == null ? 1.4 : o.rw;
      for (var i = 0; i < o.rules.length; i += 1) {
        var y = r.y + r.h * o.rules[i];
        cx.beginPath(); cx.moveTo(r.x + r.w * 0.08, y);
        cx.lineTo(r.x + r.w * 0.92, y); cx.stroke();
      }
    }
    cx.restore();
  };

  N.rng = function (salt) { return TX.rng(N.SEED + (salt || 0)); };

  /* --------------------------------------------------------------------- camera
   *
   * THE DECK'S CAMERA, HANDED TO A FRAME WITH THE DECK'S OWN LIGHT ALREADY IN IT. A frame may
   * move the eye and the horizon, which is a CAMERA MOVE and is one of this deck's continuity
   * devices. It may not move the light, because `depth_floor` fails a frame whose scene light
   * disagrees with the chassis declaration and two surfaces holding their own copy of one rule
   * is this repo's oldest defect.
   */
  N.cam = function (o) {
    if (!global.TXSCENE) throw new Error("gensetyard.cam needs txscene.js on this frame");
    o = o || {};
    var d = TXDECK.deck();
    return {
      w: N.W, h: N.H,
      eye:     o.eye     == null ? 1.65 : o.eye,
      horizon: o.horizon == null ? 700  : o.horizon,
      f:       o.f       == null ? 900  : o.f,
      sky:     o.sky     || N.G.voidd,
      fogZ:    o.fogZ    == null ? 1e9 : o.fogZ,
      light:   { az: d.light.az, el: d.light.el }
    };
  };

  N.castDir = function () { return TXDECK.castDir(); };
  N.castLen = function (h) { return TXDECK.castLen(h); };

  /* ---------------------------------------------------------------------- press
   *
   * THE DECK'S STOCK, HANDED TO A FRAME. A frame passes its own `draw` and its own `over` and
   * gets the deck's paper, ink, screen and contour. There is no drawFrame here and there never
   * will be. The chassis hands a frame the press. The frame decides what goes through it.
   */
  N.print = function (cx, o) {
    if (!global.TXINK) throw new Error("gensetyard.print needs txink.js on this frame");
    o = o || {};
    TXINK.print(cx, {
      w: N.W, h: N.H,
      ground: o.ground || N.GROUND,
      ink:    o.ink    || N.INK,
      fibre:  o.fibre  == null ? 0.05 : o.fibre,
      screen: o.screen || N.SCREEN,
      edges:  o.edges  || N.EDGES,
      seed:   o.seed   == null ? 32 : o.seed,
      draw:   o.draw,
      over:   o.over
    });
  };

  /* ------------------------------------------------------------------ type seating
   *
   * ONE WAY OF SEATING TYPE, AND IT IS A RESERVE RATHER THAN A PLATE. The art is told where the
   * type goes BEFORE it draws, every field multiplies its density by the mask, and a layer that
   * can't consult a mask as it goes gets quieted afterwards.
   */
  N.boxes = function (sel, pad) {
    return TXDECK.lineBoxes(sel || ".hook, .dek, .kick, .count, .src, .tx-site",
                            pad == null ? 18 : pad);
  };
  N.mask = function (boxes, feather) {
    return TXDECK.reserveMask(boxes, feather == null ? 28 : feather);
  };

  /* QUIET THE ART BEHIND A LINE OF TYPE, AND IT IS A WASH RATHER THAN A PLATE.
   *
   * This deck is nine drawn worlds with real horizontal geometry in them: a skid rail, a fence
   * top rail, a horizon cut, the edge of a sheet, a window sill. Every one of those is a long
   * edge, and wherever one crosses a glyph band the QA harness reads it as a strikethrough,
   * correctly, because at feed width that is what it looks like. Moving real geometry to dodge
   * the furniture would be drawing the world around the type, which is backwards.
   *
   * SO THE LIGHT DIMS TOWARD THE TYPE. A soft falloff over each measured line box, in the deck's
   * own ground, capped well under the 0.55 alpha `deck_chassis.py` fails the build on, and
   * feathered over the full height of the box again above and below it.
   */
  /* THE FURNITURE BAND RESERVE. The kicker, the counter and the source line live in a fixed
   * band top and bottom, and the print is faded to the deck's own ground under them so those
   * lines never sit on a screen. */
  N.reserve = function (c, o) {
    o = o || {};
    TXINK.reserve(c, {
      ground: o.ground || N.GROUND,
      top: o.top == null ? 150 : o.top,
      topSolid: o.topSolid == null ? 92 : o.topSolid,
      bottom: o.bottom == null ? 150 : o.bottom,
      bottomSolid: o.bottomSolid == null ? 94 : o.bottomSolid
    });
  };

  /* QUIET IS CALLED ON `over`'s CONTEXT AND NEVER ON THE TWIN, AND THAT IS NOT A STYLE NOTE.
   *
   * Called inside `draw`, this paints its gradients into the offscreen twin, and TXINK's edge
   * pass then runs a Sobel over that twin and lays the RESULT as contour ink. So the reserve's
   * own soft boundaries come back as hairline rules lying exactly across the type they were
   * drawn to protect, and machine QA reports them as strikethroughs. It is right to: at feed
   * width that is what they are. This deck's first full pass reported 74 strikes across eight
   * frames from precisely that, and every one of them was the reserve striking its own type.
   *
   * Called on `over`, it dims the finished print after the screen and the contour have run.
   */
  N.quiet = function (c, boxes, alpha) {
    if (!boxes || !boxes.length) return;
    var A = alpha == null ? 0.42 : Math.min(0.50, alpha);
    var g = [parseInt(N.GROUND.slice(1, 3), 16),
             parseInt(N.GROUND.slice(3, 5), 16),
             parseInt(N.GROUND.slice(5, 7), 16)];
    /* TXDECK.lineBoxes RETURNS ARRAYS [x, y, w, h] AND NOT OBJECTS. Reading b.y off one of
     * these yields undefined, the gradient goes NaN, and the wash paints at the origin. */
    c.save();
    for (var i = 0; i < boxes.length; i += 1) {
      var b = boxes[i];
      var x = b[0], y = b[1], w = b[2], h = b[3];
      var gr = c.createLinearGradient(0, y - h, 0, y + h * 2);
      gr.addColorStop(0.00, "rgba(" + g[0] + "," + g[1] + "," + g[2] + ",0)");
      gr.addColorStop(0.34, "rgba(" + g[0] + "," + g[1] + "," + g[2] + "," + A + ")");
      gr.addColorStop(0.66, "rgba(" + g[0] + "," + g[1] + "," + g[2] + "," + A + ")");
      gr.addColorStop(1.00, "rgba(" + g[0] + "," + g[1] + "," + g[2] + ",0)");
      c.fillStyle = gr;
      c.fillRect(x - 40, y - h, w + 80, h * 3);
    }
    c.restore();
  };

  global.YARD = N;
})(this);
